/**
 * 给「先用 AI 把资料转成 JSON」这条路用的提示词。
 *
 * 为什么留这条路：应用内置的解析器认的是「一、填空题 / 二、选择题」这套版式，
 * 碰上扫描件（整页图片）、双栏乱序、表格排版的书，规则会失手。
 * 这时候把文字丢给任意大模型、让它按下面的格式吐 JSON，粘回来就能导入。
 *
 * 提示词里刻意只放一份示例（字段名出现次数很少），
 * 免得发布守卫把它当成「夹带了整份题库」——scripts/check_release.mjs 会数 "stem": 出现次数。
 */

/** 可以整段复制进对话框的提示词；`{资料}` 由用户替换成实际内容 */
export const AI_PROMPT = `你是一个题库整理助手。下面是一份考试复习资料的文字（从 PDF / Word 里复制出来的，可能有断行、页眉页脚、题号错乱）。请把它整理成 KillQuestion 可以直接导入的 JSON。

硬性要求：
1. 只输出 JSON 本体。不要解释、不要 Markdown 代码围栏、不要在前后加任何说明文字。
2. 严格照抄原文，不要改写、缩写、总结，也不要补充原文没有的内容。题干里的空位保留成「（ ）」。
3. 按原文顺序整理：一、填空题 → 二、选择题 → 三、判断题 → 四、简答题 → 五、论述题（原文没有的小节跳过）。
4. 如果原文缺答案，就把答案留空（填空留空字符串），绝对不要自己编答案。
5. 遇到读不通的地方（页眉页脚、「第 3 页 共 159 页」、目录里的省略号行），直接丢掉。

输出结构（下面是格式示例，题干与答案都是我编的占位文字，不要抄进结果）：
{
  "version": 1,
  "topics": [],
  "questions": [
    {
      "id": "Q0001",
      "type": "fill",
      "no": 1,
      "section": "fill",
      "sectionLabel": "填空题",
      "stem": "示例题干，括号里是一个空位（ ）。",
      "answer": ["示例答案"],
      "answerText": "示例答案",
      "blanks": 1,
      "topicIds": []
    }
  ]
}

字段说明：
- id：从 Q0001 开始按顺序编号，不能重复。
- type：single 单选 / multi 多选 / judge 判断 / fill 填空 / short 简答 / essay 论述。
- section：填空题填 fill、选择题填 choice、判断题填 judge、简答题填 short、论述题填 essay；sectionLabel 分别填「填空题」「选择题」「判断题」「简答题」「论述题」。
- no：原书题号（同一小节内从 1 开始）。
- stem：题干原文。
- 选择题要带 options 数组，形如 [{"key":"A","text":"选项原文"},{"key":"B","text":"选项原文"}]，answer 填正确选项的字母数组；多选题就是 ["A","C"] 这种多字母。
- 判断题的 answer 只填 ["正确"] 或 ["错误"]，answerText 填同样的字；原文用 √ / × 的，也照样转成「正确 / 错误」。
- 填空题的 answer 是逐空答案数组（first 空、second 空…的顺序），blanks 是空位数量。
- 简答题 / 论述题把整段答案放在 answerText 里，answer 填 ["同样的整段答案"]。
- 论述题如果有多个小问共用的材料，把材料放在 material 字段里，题干只留小问。
- 如果另外有一份「划重点」清单，把每条考点抄进 topics，形如 [{"id":"k01","section":"一、分组名","title":"考点名称","count":0}]；再把相关题目的 topicIds 填上对应考点 id。没有考点就让 topics 是空数组、topicIds 都是空数组。
- meta 不用写，程序导入时会自己统计。

我提供的资料如下：
{资料}`;

